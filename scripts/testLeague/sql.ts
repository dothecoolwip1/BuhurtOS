/**
 * SQL emitters. Base tables (sources, organization, seasons, teams, fighters, events) are written by the loader role. Everything an
 * organizer does (linking the event to its season and organization, competitions, entries, rosters, matches, results) runs AS THE OWNER
 * through the product's own RLS, grants and RPCs: set_event_season, set_event_organization, set_entry_roster, finalize_match, finish_competition.
 * The owner's auth user id is the placeholder __OWNER_ID__, replaced when the file is loaded.
 */
import type { World, EventWorld } from './world';
import type { FighterDef, TeamDef } from './roster';
import type { PlayedMatch, CompSim } from './play';
import { resolved } from './play';
import { SEASONS, type EventDef } from './events';
import { q, qArr, qJson, uid } from './util';
import type { Bio } from './bios';

export const SOURCE_ID = uid('source|NACL-test fictional dataset');
export const ORG_ID = uid('organization|nacl-test');
export const seasonId = (y: number): string => uid(`season|${y}`);
const NOTE = 'NACL-test fictional dataset';
const OWNER = `set local role authenticated;\nselect set_config('request.jwt.claims', '{"sub":"__OWNER_ID__","role":"authenticated"}', true);`;
const HEADER = (what: string): string => `-- NACL-test fictional dataset: ${what}. Everything here is fictional (names end in -test). Generated by scripts/testLeague; do not edit by hand.\n-- Replace __OWNER_ID__ with the platform owner's auth user id before running. Safe to run again.\n`;

const rs = (type: string, idExpr: string, note: string = NOTE): string =>
  `(${q(SOURCE_ID)}, ${q(type)}, ${idExpr}, 'unverified', ${q(note)})`;
const RS_COLS = 'insert into public.record_sources (source_id, entity_type, entity_id, status, note) values';

export function coreFile(w: World): string {
  const o: string[] = [HEADER('organization, seasons, source, teams and affiliations'), 'begin;'];
  o.push(`insert into public.sources (id, kind, title, citation, retrieved_on) values (${q(SOURCE_ID)}, 'submitted', 'NACL-test fictional dataset', 'Generated by scripts/testLeague (deterministic). Fictional: no real people, teams, events or results.', date '2026-10-01') on conflict (id) do nothing;`);
  o.push(`insert into public.organizations (id, slug, name, kind, country, short_name, region, description) values (${q(ORG_ID)}, 'nacl-test', 'Northern Armored Combat League-test', 'regional', 'Canada', 'NACL-test', 'Western Canada',
${q('A regional governing organization formed by several Western Canadian armored combat clubs that wanted a shared competition calendar, consistent tournament standards, regional rankings, fighter records and easier travel between clubs. Alberta-heavy at first, it gradually expanded its relationships into British Columbia, Saskatchewan and Manitoba. Fictional test dataset.')}) on conflict (id) do nothing;`);
  o.push(`insert into public.seasons (id, organization_id, slug, name, starts_on, ends_on) values\n${SEASONS.map(y => `  (${q(seasonId(y))}, ${q(ORG_ID)}, 'nacl-test-${y}', 'NACL-test ${y} Season', date '${y}-01-01', date '${y}-12-31')`).join(',\n')}\non conflict (id) do nothing;`);
  o.push(`insert into public.teams (id, slug, name, city, region, country, colors, crest_division, initial, status, description, founded_year) values\n${w.teams.map(t =>
    `  (${q(t.id)}, ${q(t.slug)}, ${q(t.name)}, ${q(t.city)}, ${q(t.prov)}, 'CA', array['${t.colors[0]}', '${t.colors[1]}'], '${t.crest}', '${t.initial}', 'approved', ${q(t.blurb)}, ${t.foundedYear})`).join(',\n')}\non conflict (id) do nothing;`);
  const aff = (t: TeamDef): string => uid(`affiliation|${t.name}`);
  o.push(`insert into public.team_affiliations (id, team_id, organization_id, relation, from_date) values\n${w.teams.map(t => `  (${q(aff(t))}, ${q(t.id)}, ${q(ORG_ID)}, 'member', date '2023-01-01')`).join(',\n')}\non conflict (id) do nothing;`);
  const rows = [rs('organization', q(ORG_ID)), ...SEASONS.map(y => rs('season', q(seasonId(y)))), ...w.teams.map(t => rs('team', q(t.id))), ...w.teams.map(t => rs('team_affiliation', q(aff(t))))];
  o.push(`${RS_COLS}\n  ${rows.join(',\n  ')}\non conflict do nothing;`);
  o.push('commit;');
  return o.join('\n');
}

export const membershipId = (f: FighterDef): string => uid(`membership|${f.name}`);

export function fighterFile(w: World, part: FighterDef[], bios: Map<number, Bio>): string {
  const o: string[] = [HEADER(`fighters ${part[0].idx + 1}-${part[part.length - 1].idx + 1} with profiles and team memberships`), 'begin;'];
  o.push(`insert into public.fighters (id, display_name, team_id, gender, birth_year, city, region, country, joined_year, disciplines, fighting_style, bio, highlights) values\n${part.map(f => {
    const b = bios.get(f.idx)!;
    return `  (${q(f.id)}, ${q(f.name)}, ${q(w.teams[f.teamIdx].id)}, '${f.sex}', ${f.birthYear}, ${q(f.city)}, ${q(f.prov)}, 'CA', ${f.joinedYear}, ${qArr(f.disciplines)}, ${q(b.style)}, ${q(b.bio)}, ${qArr(b.highlights)})`;
  }).join(',\n')}\non conflict (id) do update set team_id = excluded.team_id, gender = excluded.gender, birth_year = excluded.birth_year, city = excluded.city, region = excluded.region,
  country = excluded.country, joined_year = excluded.joined_year, disciplines = excluded.disciplines, fighting_style = excluded.fighting_style, bio = excluded.bio, highlights = excluded.highlights;`);
  const captains = new Set(w.teams.map(t => w.fighters.filter(f => f.teamIdx === t.idx).sort((a, b) => a.joinDate.localeCompare(b.joinDate) || a.idx - b.idx)[0].idx));
  o.push(`insert into public.team_memberships (id, fighter_id, team_id, role, mercenary, from_date) values\n${part.map(f => `  (${q(membershipId(f))}, ${q(f.id)}, ${q(w.teams[f.teamIdx].id)}, '${captains.has(f.idx) ? 'captain' : 'fighter'}', false, date '${f.joinDate}')`).join(',\n')}\non conflict (id) do nothing;`);
  const rows = [
    ...part.map(f => rs('fighter', q(f.id), f.joinedAssumed ? `${NOTE}. joined_year ${f.joinedYear} is an ASSUMPTION: the owner's roster did not state it.` : NOTE)),
    ...part.map(f => rs('team_membership', q(membershipId(f))))
  ];
  o.push(`${RS_COLS}\n  ${rows.join(',\n  ')}\non conflict do nothing;`);
  o.push('commit;');
  return o.join('\n');
}

const tsLit = (local: string, tz: string): string => `(timestamp '${local}' at time zone '${tz}')`;

function matchRows(ev: EventDef, compId: string, ms: PlayedMatch[]): string {
  return `insert into public.matches (id, competition_id, stage, round_label, position, pool, entry_a, entry_b, field, scheduled_at, duration_minutes) values\n${ms.map(m =>
    `  (${q(m.id)}, ${q(compId)}, '${m.stage}', ${q(m.roundLabel)}, ${m.position}, ${q(m.pool)}, ${q(m.entryA)}, ${q(m.entryB)}, ${q(m.field)}, ${tsLit(m.startLocal!, ev.tz)}, ${m.duration})`).join(',\n')}\non conflict (id) do nothing;`;
}
function linkRows(ms: PlayedMatch[]): string | null {
  const l = ms.filter(m => m.nextId);
  if (!l.length) return null;
  return `update public.matches m set next_match_id = v.n, next_slot = v.s from (values\n${l.map(m => `  (${q(m.id)}::uuid, ${q(m.nextId)}::uuid, '${m.nextSlot}')`).join(',\n')}\n) v(id, n, s) where m.id = v.id and m.next_match_id is null;`;
}
const finalizeSql = (m: PlayedMatch): string => {
  const o = m.outcome!;
  return `select public.finalize_match(m.id, '${o.result}', ${o.scoreA}, ${o.scoreB}, ${qJson(o.detail)}, m.version) from public.matches m where m.id = ${q(m.id)} and m.queue_state <> 'final';`;
};

export function eventFile(w: World, ew: EventWorld, hostId: string | null): string {
  const ev = ew.event;
  const played = !ev.current;
  const o: string[] = [HEADER(`${ev.name}${played ? ' (completed)' : ' (current: drawn and scheduled, nothing final)'}`), 'begin;'];
  o.push(`insert into public.events (id, slug, name, description, event_type, status, venue, city, region, country, timezone, fee_cents, starts_on, ends_on, host_team_id, registration_mode, time_note) values
  (${q(ev.id)}, ${q(ev.slug)}, ${q(ev.name)}, ${q(ev.description)}, 'tournament', 'published', ${q(ev.venue)}, ${q(ev.city)}, ${q(ev.prov)}, 'CA', ${q(ev.tz)}, 0, date '${ev.start}', date '${ev.end}', ${q(hostId)}, 'none', ${q('Fictional test event. Entries were recorded by the organizer; there is no registration form.')})
on conflict (id) do nothing;`);
  o.push(`${RS_COLS}\n  ${rs('event', q(ev.id))}\non conflict do nothing;`);
  o.push(OWNER);
  o.push(`select public.set_event_season(${q(ev.id)}, ${q(seasonId(Number(ev.start.slice(0, 4))))});\nselect public.set_event_organization(${q(ev.id)}, ${q(ORG_ID)});`);
  o.push(`insert into public.competitions (id, event_id, name, category, gender, tier, ruleset, structure, status, rounds_to_win, sort) values\n${ew.sims.map((s, i) => {
    const c = s.comp, duel = c.div.cat !== '5v5' && c.div.cat !== '3v3';
    return `  (${q(c.id)}, ${q(ev.id)}, ${q(c.name)}, '${c.div.cat}', '${c.div.gender}', '${ev.tier}', ${q(duel ? 'Buhurt International: Duels rules V.26.4' : 'Buhurt International: Buhurt Rules V.26.4.1')}, '${s.structure}', '${played ? 'running' : 'registration'}', ${s.roundsToWin ?? 'null'}, ${(i + 1) * 10})`;
  }).join(',\n')}\non conflict (id) do nothing;`);
  const status = played ? 'checked_in' : 'registered';
  const ent: string[] = [];
  for (const s of ew.sims) for (const e of s.comp.entries) ent.push(`  (${q(e.id)}, ${q(s.comp.id)}, ${q(e.teamIdx === null ? null : w.teams[e.teamIdx].id)}, ${q(e.fighterIdx === null ? null : w.fighters[e.fighterIdx].id)}, '${status}')`);
  o.push(`insert into public.entries (id, competition_id, team_id, fighter_id, status) values\n${ent.join(',\n')}\non conflict (id) do nothing;`);
  for (const s of ew.sims) for (const e of s.comp.entries) {
    if (e.teamIdx === null) continue;
    const roster = e.roster.map(r => ({ fighter_id: w.fighters[r.fighterIdx].id, role: r.role }));
    o.push(`select public.set_entry_roster(${q(e.id)}, ${qJson(roster)}) where exists (select 1 from public.competitions where id = ${q(s.comp.id)} and status <> 'finished');`);
  }
  for (const s of ew.sims) o.push(...compMatches(ev, s, played));
  o.push('reset role;');
  o.push(`${RS_COLS}\n  ${ew.sims.map(s => rs('competition', q(s.comp.id))).join(',\n  ')}\non conflict do nothing;`);
  if (played) {
    o.push(`insert into public.record_sources (source_id, entity_type, entity_id, status, note) select ${q(SOURCE_ID)}, 'result', r.id, 'unverified', ${q(NOTE)} from public.results r join public.competitions c on c.id = r.competition_id where c.event_id = ${q(ev.id)} on conflict do nothing;`);
    // Make the history look like history: matches were finished at their scheduled time, audit entries on the weekend.
    o.push(`update public.matches m set finalized_at = m.scheduled_at + make_interval(mins => m.duration_minutes) from public.competitions c where c.id = m.competition_id and c.event_id = ${q(ev.id)} and m.queue_state = 'final';`);
    o.push(`update public.audit_log set at = (date '${ev.end}' + time '21:00') at time zone ${q(ev.tz)} where event_id = ${q(ev.id)};`);
  }
  o.push('commit;');
  return o.join('\n');
}

function compMatches(ev: EventDef, s: CompSim, played: boolean): string[] {
  const o: string[] = [`-- ${s.comp.name}: ${s.structure}, ${s.comp.entries.length} entries`];
  for (const phase of s.phases) {
    o.push(matchRows(ev, s.comp.id, phase));
    const l = linkRows(phase);
    if (l) o.push(l);
    if (played) for (const m of phase) { void resolved(m); o.push(finalizeSql(m)); }
  }
  if (played) o.push(`select public.finish_competition(${q(s.comp.id)}, 'tournament_structure') where exists (select 1 from public.competitions where id = ${q(s.comp.id)} and status <> 'finished');`);
  return o;
}
