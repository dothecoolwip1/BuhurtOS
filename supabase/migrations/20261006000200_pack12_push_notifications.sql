-- "What matters right now" for the Home screen: the person's most pressing called fight in an event that is on today. The same columns the field queue,
-- My next fight and the alerts read, so Home, the screen and the lock screen cannot disagree. Opponent names are the public entry names.
create or replace function public.my_fight_now()
returns table (event_slug text, event_name text, competition_name text, field text, stage text, opponent text)
language sql stable security definer set search_path = '' as $$
  with ev as (
    select e.id, e.slug, e.name from public.events e
    where auth.uid() is not null and e.status = 'published' and (now() at time zone e.timezone)::date between e.starts_on and e.ends_on),
  mine as (select ev.id as event_id, ev.slug, ev.name, x.entry_id from ev cross join lateral public.my_event_entries(ev.id) x)
  select mine.slug, mine.name, k.name, coalesce(nullif(btrim(m.field), ''), 'Field 1'), m.queue_state,
         case when m.entry_a = mine.entry_id then coalesce(tb.name, fb.display_name) else coalesce(ta.name, fa.display_name) end
  from mine
  join public.matches m on mine.entry_id in (m.entry_a, m.entry_b) and m.queue_state in ('active', 'on_deck', 'in_the_hole')
  join public.competitions k on k.id = m.competition_id and k.event_id = mine.event_id
  left join public.entries ea on ea.id = m.entry_a left join public.teams ta on ta.id = ea.team_id left join public.fighters fa on fa.id = ea.fighter_id
  left join public.entries eb on eb.id = m.entry_b left join public.teams tb on tb.id = eb.team_id left join public.fighters fb on fb.id = eb.fighter_id
  order by case m.queue_state when 'active' then 0 when 'on_deck' then 1 else 2 end, m.id
  limit 1
$$;
revoke execute on function public.my_fight_now() from public, anon;
grant execute on function public.my_fight_now() to authenticated;

-- ---------------------------------------------------------------- 5. the dispatcher's two doors (service role only)
create or replace function public.push_dispatch_config() returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'secret', (select value from private.push_config where key = 'dispatch_secret'),
    'vapid_public', (select value from private.push_config where key = 'vapid_public'),
    'vapid_private', (select value from private.push_config where key = 'vapid_private'),
    'subject', (select value from private.push_config where key = 'vapid_subject'))
$$;

-- Stores a key pair only when none exists, so two dispatchers starting together cannot replace each other's keys (that would orphan every subscription).
create or replace function public.push_store_vapid(p_public text, p_private text) returns boolean
language plpgsql security definer set search_path = '' as $$
declare v_n integer;
begin
  if p_public is null or p_private is null or char_length(p_public) < 80 or char_length(p_private) < 40 then raise exception 'not a key pair' using errcode = '22023'; end if;
  insert into private.push_config (key, value) values ('vapid_public', p_public) on conflict (key) do nothing;
  get diagnostics v_n = row_count;
  if v_n = 0 then return false; end if;
  insert into private.push_config (key, value) values ('vapid_private', p_private) on conflict (key) do nothing;
  return true;
end $$;

-- How long a notification is still worth showing. A fight alert that arrives an hour late is worse than none.
create or replace function private.push_ttl(p_category text) returns interval
language sql immutable set search_path = '' as $$ select case p_category when 'fights' then interval '10 minutes' else interval '24 hours' end $$;
revoke execute on function private.push_ttl(text) from public, anon, authenticated;

-- Hands the dispatcher the next batch: one row per (notification, device). A pair is claimed by exactly one dispatcher (the insert is the lock), a send that
-- died is picked up again after two minutes, and a pair is tried at most four times. Notifications nobody can receive (no device, or that group switched off)
-- and notifications past their useful life are closed without sending.
create or replace function public.push_claim(p_limit integer default 100) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_out jsonb;
begin
  update public.push_deliveries set state = 'failed', last_error = coalesce(last_error, 'no answer from the dispatcher'), updated_at = now()
  where state in ('sending', 'retry') and attempts >= 4 and claimed_at < now() - interval '2 minutes';
  update public.notifications set push_state = 'done' where push_state = 'pending' and created_at < now() - private.push_ttl(category);
  update public.notifications n set push_state = 'done'
  where n.push_state = 'pending' and exists (select 1 from public.push_deliveries d where d.notification_id = n.id)
    and not exists (select 1 from public.push_deliveries d where d.notification_id = n.id and d.state in ('sending', 'retry'));

  update public.notifications n set push_state = 'done'
  where n.push_state = 'pending'
    and not exists (
      select 1 from public.push_subscriptions s
      left join public.notification_preferences p on p.user_id = s.user_id
      where s.user_id = n.user_id and s.revoked_at is null
        and coalesce(case n.category when 'fights' then p.fights when 'team' then p.team when 'events' then p.events else p.system end, true));

  with pending as (
    select n.id, n.user_id, n.category from public.notifications n
    where n.push_state = 'pending' order by n.created_at limit greatest(1, least(coalesce(p_limit, 100), 500)) for update skip locked),
  pairs as (
    select pe.id as nid, s.id as sid from pending pe
    join public.push_subscriptions s on s.user_id = pe.user_id and s.revoked_at is null
    left join public.notification_preferences p on p.user_id = pe.user_id
    where coalesce(case pe.category when 'fights' then p.fights when 'team' then p.team when 'events' then p.events else p.system end, true)),
  claimed as (
    insert into public.push_deliveries as d (notification_id, subscription_id)
    select nid, sid from pairs
    on conflict (notification_id, subscription_id) do update
      set state = 'sending', attempts = d.attempts + 1, claimed_at = now(), updated_at = now()
      where d.attempts < 4 and (d.state = 'retry' or (d.state = 'sending' and d.claimed_at < now() - interval '2 minutes'))
    returning d.notification_id, d.subscription_id)
  select coalesce(jsonb_agg(jsonb_build_object(
    'notification_id', c.notification_id, 'subscription_id', c.subscription_id,
    'endpoint', s.endpoint, 'p256dh', s.p256dh, 'auth', s.auth,
    'title', t.title, 'body', t.body, 'route', coalesce(n.route, '/'), 'category', n.category,
    'tag', case when n.payload ? 'match_id' then 'fight-' || (n.payload ->> 'match_id') else 'n-' || n.id::text end,
    'urgent', n.category = 'fights', 'ttl', extract(epoch from private.push_ttl(n.category))::integer)), '[]'::jsonb)
  into v_out
  from claimed c join public.notifications n on n.id = c.notification_id join public.push_subscriptions s on s.id = c.subscription_id
  cross join lateral private.notification_text(n.kind, n.payload) t;
  return v_out;
end $$;

-- The dispatcher reports what happened. gone = the push service said the device no longer exists (it is revoked at once); failed = gave up.
create or replace function public.push_report(p_results jsonb) returns integer
language plpgsql security definer set search_path = '' as $$
declare r record; v_n integer := 0; v_state text;
begin
  for r in select (x ->> 'notification_id')::uuid as nid, (x ->> 'subscription_id')::uuid as sid, x ->> 'outcome' as outcome, left(x ->> 'error', 200) as err
           from jsonb_array_elements(coalesce(p_results, '[]'::jsonb)) x loop
    v_state := case r.outcome when 'sent' then 'sent' when 'gone' then 'gone' when 'retry' then 'retry' else 'failed' end;
    update public.push_deliveries d set
      state = case when v_state = 'retry' and d.attempts >= 4 then 'failed' else v_state end, last_error = r.err, updated_at = now()
    where d.notification_id = r.nid and d.subscription_id = r.sid;
    if v_state = 'sent' then
      update public.push_subscriptions set last_success_at = now(), failure_count = 0 where id = r.sid;
    elsif v_state = 'gone' then
      perform private.revoke_subscription(r.sid);
    elsif v_state in ('failed', 'retry') then
      update public.push_subscriptions set failure_count = failure_count + 1 where id = r.sid;
      -- A device that has failed this many times in a row is treated as gone; its owner can simply turn notifications on again.
      if (select failure_count from public.push_subscriptions where id = r.sid) >= 12 then perform private.revoke_subscription(r.sid); end if;
    end if;
    v_n := v_n + 1;
  end loop;
  update public.notifications n set push_state = 'done'
  where n.push_state = 'pending'
    and exists (select 1 from public.push_deliveries d where d.notification_id = n.id)
    and not exists (select 1 from public.push_deliveries d where d.notification_id = n.id and d.state in ('sending', 'retry'));
  return v_n;
end $$;

-- Housekeeping reads for the dispatcher: tombstones and old read notifications it may clean up with its own service key.
revoke execute on function public.push_dispatch_config(), public.push_store_vapid(text, text), public.push_claim(integer), public.push_report(jsonb) from public, anon, authenticated;
grant execute on function public.push_dispatch_config(), public.push_store_vapid(text, text), public.push_claim(integer), public.push_report(jsonb) to service_role;

-- ---------------------------------------------------------------- 6. who is a person's fight? (the same rule as my_event_entries, read the other way round)
-- A fighter entry belongs to that fighter's account. A team entry belongs to the accounts of the fighters on its RECORDED roster for that competition
-- (never to whoever is on the team today); only while no roster is recorded does the registration stand in. Withdrawn / disqualified entries notify nobody.
create or replace function private.entry_recipient_users(p_entry uuid) returns setof uuid
language sql stable security definer set search_path = '' as $$
  with e as (
    select en.id, en.team_id, en.fighter_id, en.competition_id, k.event_id
    from public.entries en join public.competitions k on k.id = en.competition_id
    where en.id = p_entry and en.status in ('registered', 'checked_in'))
  select fa.user_id from e join public.fighter_accounts fa on fa.fighter_id = e.fighter_id
  union
  select fa.user_id from e join public.entry_fighters ef on ef.entry_id = e.id join public.fighter_accounts fa on fa.fighter_id = ef.fighter_id
  where e.team_id is not null
  union
  select r.user_id
  from e join public.registrations r on r.event_id = e.event_id and r.status = 'accepted' and not r.is_volunteer and r.user_id is not null
  where e.team_id is not null and not exists (select 1 from public.entry_fighters ef where ef.entry_id = e.id)
    and (
      exists (select 1 from public.registrations r2 join public.registration_competitions rc on rc.registration_id = r2.id
              where r2.user_id = r.user_id and r2.event_id = e.event_id and r2.status = 'accepted' and not r2.is_volunteer
                and rc.competition_id = e.competition_id and rc.team_id = e.team_id)
      or (e.team_id in (select r3.team_id from public.registrations r3 where r3.user_id = r.user_id and r3.event_id = e.event_id and r3.status = 'accepted' and not r3.is_volunteer and r3.team_id is not null)
          and not exists (select 1 from public.registrations r4 join public.registration_competitions rc2 on rc2.registration_id = r4.id
                          where r4.user_id = r.user_id and r4.event_id = e.event_id and r4.status = 'accepted' and not r4.is_volunteer))
    )
$$;
revoke execute on function private.entry_recipient_users(uuid) from public, anon, authenticated;

-- ---------------------------------------------------------------- 7. fight notifications from real queue transitions
-- Runs at COMMIT of the transaction that moved the match (deferred), so it sees the final state of every change in it and a match moved twice in one
-- transaction (a swap) is reported once, by where it ended up. Triggers on the real columns, so it covers every way the queue changes: automatic
-- advancement after a result, "start next", run sooner / later / skip, set_match_queue, send back to line, planner and field changes.
--   moved up (in the hole / on deck / now) -> fight_called with that stage
--   moved back while it had been called        -> fight_moved 'back'
--   same state but a different field, while called -> fight_moved 'field'
--   becoming final                             -> the earlier alerts for that match are marked read (nothing is sent)
-- The same person is not sent the same stage for the same match twice within two minutes, and a newer alert marks the older unread ones for that match read,
-- so a lock screen and the bell do not pile up contradictory messages. A failure here is logged and NEVER blocks the queue (see the exception handler).
create or replace function private.queue_notify() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_cur public.matches; v_ev public.events; v_comp text; v_old integer; v_new integer; v_stage text; v_kind text; v_field text; v_payload jsonb; v_u uuid;
begin
  begin
    select * into v_cur from public.matches where id = new.id;
    if not found or v_cur.queue_state is distinct from new.queue_state then return null; end if;      -- a later change in this transaction speaks for the match

    if new.queue_state = 'final' then
      update public.notifications set read_at = coalesce(read_at, now()) where kind in ('fight_called', 'fight_moved') and read_at is null and payload ->> 'match_id' = new.id::text;
      return null;
    end if;
    if old.queue_state = 'final' then return null; end if;

    v_old := case old.queue_state when 'in_the_hole' then 1 when 'on_deck' then 2 when 'active' then 3 else 0 end;
    v_new := case new.queue_state when 'in_the_hole' then 1 when 'on_deck' then 2 when 'active' then 3 else 0 end;
    if v_new > v_old then v_kind := 'fight_called'; v_stage := new.queue_state;
    elsif v_new < v_old then v_kind := 'fight_moved'; v_stage := 'back';
    elsif v_new > 0 and private.field_key(old.field) is distinct from private.field_key(new.field) then v_kind := 'fight_moved'; v_stage := 'field';
    else return null; end if;

    select e.* into v_ev from public.events e join public.competitions k on k.event_id = e.id where k.id = new.competition_id;
    select k.name into v_comp from public.competitions k where k.id = new.competition_id;
    v_field := coalesce(nullif(btrim(new.field), ''), 'Field 1');
    v_payload := jsonb_build_object('match_id', new.id, 'stage', v_stage, 'field', v_field, 'competition_name', v_comp, 'event_name', v_ev.name, 'event_slug', v_ev.slug);

    for v_u in select x from private.entry_recipient_users(new.entry_a) x union select y from private.entry_recipient_users(new.entry_b) y loop
      if exists (select 1 from public.notifications n where n.user_id = v_u and n.kind = v_kind and n.payload ->> 'match_id' = new.id::text
                 and n.payload ->> 'stage' = v_stage and n.payload ->> 'field' = v_field and n.created_at > now() - interval '2 minutes') then continue; end if;
      update public.notifications set read_at = coalesce(read_at, now())
      where user_id = v_u and kind in ('fight_called', 'fight_moved') and read_at is null and payload ->> 'match_id' = new.id::text;
      insert into public.notifications (user_id, kind, payload) values (v_u, v_kind, v_payload);
    end loop;
  exception when others then
    raise warning 'fight notification failed for match %: %', new.id, sqlerrm;
  end;
  return null;
end $$;
revoke execute on function private.queue_notify() from public, anon, authenticated;

do $do$
begin
  if not exists (select 1 from pg_trigger where tgname = 'matches_notify_queue' and tgrelid = 'public.matches'::regclass) then
    create constraint trigger matches_notify_queue after update of queue_state, field on public.matches
      deferrable initially deferred for each row
      when (old.queue_state is distinct from new.queue_state or coalesce(old.field, '') is distinct from coalesce(new.field, ''))
      execute function private.queue_notify();
  end if;
end $do$;

-- ---------------------------------------------------------------- 8. team and event activity
-- Someone joins a team: the captain(s) hear, except the person who did it. The fighter hears when someone else added them (a join they asked for is
-- already answered by "your request was approved"). Nothing is sent for bulk or system work (no signed-in actor), for coaches/squires/mercenaries,
-- or for test teams.
create or replace function private.membership_notify() returns trigger
language plpgsql security definer set search_path = '' as $$
declare v_team public.teams; v_name text; v_user uuid; v_actor uuid := auth.uid();
begin
  begin
    if v_actor is null or new.role <> 'fighter' or new.mercenary then return null; end if;
    select * into v_team from public.teams where id = new.team_id;
    if not found or v_team.status <> 'approved' then return null; end if;
    select display_name into v_name from public.fighters where id = new.fighter_id;
    select user_id into v_user from public.fighter_accounts where fighter_id = new.fighter_id;
    insert into public.notifications (user_id, kind, payload)
    select tr.user_id, 'team_member_joined', jsonb_build_object('team_id', v_team.id, 'team_name', v_team.name, 'team_slug', v_team.slug, 'fighter_name', v_name)
    from public.team_roles tr where tr.team_id = new.team_id and tr.user_id is distinct from v_actor and tr.user_id is distinct from v_user;
    if v_user is not null and v_user is distinct from v_actor
       and not exists (select 1 from public.notifications n where n.user_id = v_user and n.kind = 'team_join_decided' and n.payload ->> 'team_id' = new.team_id::text and n.created_at > now() - interval '2 minutes') then
      insert into public.notifications (user_id, kind, payload) values (v_user, 'team_member_added', jsonb_build_object('team_id', v_team.id, 'team_name', v_team.name, 'team_slug', v_team.slug));
    end if;
  exception when others then
    raise warning 'team notification failed: %', sqlerrm;
  end;
  return null;
end $$;
revoke execute on function private.membership_notify() from public, anon, authenticated;
do $do$
begin
  if not exists (select 1 from pg_trigger where tgname = 'team_memberships_notify' and tgrelid = 'public.team_memberships'::regclass) then
    create trigger team_memberships_notify after insert on public.team_memberships for each row execute function private.membership_notify();
  end if;
end $do$;

-- An event is cancelled: the people who were accepted for it hear once.
create or replace function private.event_cancel_notify() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  begin
    insert into public.notifications (user_id, kind, payload, dedupe_key)
    select distinct r.user_id, 'event_cancelled', jsonb_build_object('event_name', new.name, 'event_slug', new.slug), 'event_cancelled:' || new.id::text || ':' || r.user_id::text
    from public.registrations r where r.event_id = new.id and r.status = 'accepted' and r.user_id is not null
    on conflict (dedupe_key) where dedupe_key is not null do nothing;
  exception when others then
    raise warning 'event cancellation notice failed: %', sqlerrm;
  end;
  return null;
end $$;
revoke execute on function private.event_cancel_notify() from public, anon, authenticated;
do $do$
begin
  if not exists (select 1 from pg_trigger where tgname = 'events_cancel_notify' and tgrelid = 'public.events'::regclass) then
    create trigger events_cancel_notify after update of status on public.events for each row
      when (new.status = 'cancelled' and old.status is distinct from 'cancelled') execute function private.event_cancel_notify();
  end if;
end $do$;
