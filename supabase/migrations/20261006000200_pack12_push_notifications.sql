-- ---------------------------------------------------------------- 2. what a notification says and where a tap goes (one place, used by the list and by push)
create or replace function private.notification_category(p_kind text) returns text
language sql immutable set search_path = '' as $$
  select case
    when p_kind in ('fight_called', 'fight_moved') then 'fights'
    when p_kind in ('team_join_requested', 'team_join_decided', 'team_proposed', 'team_member_joined', 'team_member_added') then 'team'
    when p_kind in ('registration_submitted', 'registration_decided', 'registration_withdrawn', 'event_invited', 'event_cancelled') then 'events'
    else 'system' end $$;

-- Only these are worth a lock-screen alert. Organizer firehose items (sign-ups, withdrawals, proposed teams, bug reports, claim requests) stay in the app.
create or replace function private.notification_pushable(p_kind text) returns boolean
language sql immutable set search_path = '' as $$
  select p_kind in ('fight_called', 'fight_moved', 'team_join_requested', 'team_join_decided', 'team_member_joined', 'team_member_added',
                    'registration_decided', 'event_invited', 'event_cancelled', 'fighter_claim_decided', 'test_push') $$;

create or replace function private.notification_is_synthetic(p_payload jsonb) returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(p_payload ->> 'synthetic', '') = 'true'
    or exists (select 1 from public.events e where e.slug = p_payload ->> 'event_slug' and private.is_synthetic('event', e.id))
    or exists (select 1 from public.teams t where t.slug = p_payload ->> 'team_slug' and private.is_synthetic('team', t.id)) $$;

create or replace function private.notification_route(p_kind text, p_payload jsonb) returns text
language sql immutable set search_path = '' as $$
  select case
    when p_kind in ('fight_called', 'fight_moved') and coalesce(p_payload ->> 'event_slug', '') ~ '^[a-z0-9-]+$' then '/events/' || (p_payload ->> 'event_slug') || '#my-next-fight'
    when p_kind in ('registration_decided', 'event_invited', 'event_cancelled') and coalesce(p_payload ->> 'event_slug', '') ~ '^[a-z0-9-]+$' then '/events/' || (p_payload ->> 'event_slug')
    when p_kind = 'registration_submitted' and coalesce(p_payload ->> 'event_slug', '') ~ '^[a-z0-9-]+$' then '/events/' || (p_payload ->> 'event_slug') || '/manage'
    when p_kind = 'registration_withdrawn' and coalesce(p_payload ->> 'event_slug', '') ~ '^[a-z0-9-]+$' then '/events/' || (p_payload ->> 'event_slug') || '/manage?tab=fighters'
    when p_kind in ('team_member_joined', 'team_member_added') and coalesce(p_payload ->> 'team_slug', '') ~ '^[a-z0-9-]+$' then '/teams/' || (p_payload ->> 'team_slug')
    when p_kind = 'team_join_decided' and p_payload ->> 'decision' = 'approved' and coalesce(p_payload ->> 'team_slug', '') ~ '^[a-z0-9-]+$' then '/teams/' || (p_payload ->> 'team_slug')
    when p_kind in ('team_join_requested', 'team_join_decided', 'team_proposed') then '/team-manager'
    when p_kind = 'fighter_claim_requested' then '/platform/fighters'
    when p_kind = 'fighter_claim_decided' then case when p_payload ->> 'decision' = 'approved' and coalesce(p_payload ->> 'fighter_id', '') ~ '^[0-9a-f-]{36}$' then '/fighters/' || (p_payload ->> 'fighter_id') else '/claim-profile' end
    when p_kind = 'bug_reported' then '/platform/bugs'
    when p_kind = 'test_push' then '/account'
    else '/account' end $$;

-- Short, lock-screen sized text. Fight wording follows the app's own status labels (src/lib/myFight.ts statusLabel): the same truth on both screens.
create or replace function private.notification_text(p_kind text, p_payload jsonb) returns table (title text, body text)
language plpgsql immutable set search_path = '' as $$
declare
  v_team text := left(coalesce(nullif(p_payload ->> 'team_name', ''), 'a team'), 80);
  v_event text := left(coalesce(nullif(p_payload ->> 'event_name', ''), 'the event'), 80);
  v_field text := left(coalesce(nullif(p_payload ->> 'field', ''), 'Field 1'), 40);
  v_comp text := left(coalesce(nullif(p_payload ->> 'competition_name', ''), ''), 60);
  v_who text := left(coalesce(nullif(p_payload ->> 'requester_name', ''), nullif(p_payload ->> 'fighter_name', ''), nullif(p_payload ->> 'person_name', ''), 'Someone'), 80);
begin
  if p_kind = 'fight_called' then
    if p_payload ->> 'stage' = 'in_the_hole' then
      return query select 'In the hole'::text, ('You''re coming up soon. ' || case when v_comp <> '' then v_comp || ' · ' else '' end || v_field)::text;
    elsif p_payload ->> 'stage' = 'on_deck' then
      return query select 'On deck'::text, ('You''re up next on ' || v_field || '. Get to the bullpen.')::text;
    else
      return query select 'You''re up now'::text, ('You''re up now on ' || v_field || '.')::text;
    end if;
  elsif p_kind = 'fight_moved' then
    if p_payload ->> 'stage' = 'field' then
      return query select 'Your field changed'::text, ('Your fight is now on ' || v_field || '.')::text;
    else
      return query select 'Your fight moved back'::text, 'You''re not next any more. Check BuhurtOS for your place in the line.'::text;
    end if;
  elsif p_kind = 'team_join_requested' then return query select 'Join request'::text, (v_who || ' asked to join ' || v_team || '.')::text;
  elsif p_kind = 'team_join_decided' then
    if p_payload ->> 'decision' = 'approved' then return query select 'You''re on the team'::text, ('You''re now on the roster of ' || v_team || '.')::text;
    else return query select 'Join request answered'::text, (v_team || ' declined your request to join.')::text; end if;
  elsif p_kind = 'team_member_joined' then return query select 'New teammate'::text, (v_who || ' joined ' || v_team || '.')::text;
  elsif p_kind = 'team_member_added' then return query select 'Added to a team'::text, ('You''ve been added to ' || v_team || '.')::text;
  elsif p_kind = 'team_proposed' then return query select 'Team waiting for review'::text, (v_team || ' was proposed and is waiting for review.')::text;
  elsif p_kind = 'registration_submitted' then return query select 'New sign-up'::text, (v_who || ' signed up for ' || v_event || '.')::text;
  elsif p_kind = 'registration_withdrawn' then return query select 'Sign-up withdrawn'::text, (v_who || ' withdrew from ' || v_event || '.')::text;
  elsif p_kind = 'registration_decided' then
    if p_payload ->> 'decision' = 'accepted' then return query select 'You''re in'::text, ('You''re accepted for ' || v_event || '.')::text;
    else return query select 'Registration update'::text, ('Your registration for ' || v_event || ' was declined.')::text; end if;
  elsif p_kind = 'event_invited' then return query select 'You''ve been added to an event'::text, ('The organizers added you to ' || v_event || '. Finish your registration.')::text;
  elsif p_kind = 'event_cancelled' then return query select 'Event cancelled'::text, (v_event || ' was cancelled.')::text;
  elsif p_kind = 'fighter_claim_requested' then return query select 'Profile claim'::text, 'Someone asked to claim a fighter profile.'::text;
  elsif p_kind = 'fighter_claim_decided' then
    if p_payload ->> 'decision' = 'approved' then return query select 'Profile claimed'::text, 'Your fighter profile is now yours, with its full history.'::text;
    else return query select 'Profile claim answered'::text, 'Your request to claim a fighter profile was not approved.'::text; end if;
  elsif p_kind = 'bug_reported' then return query select 'Bug report'::text, 'A new bug report was filed.'::text;
  elsif p_kind = 'test_push' then return query select 'BuhurtOS test'::text, 'Notifications are working on this device.'::text;
  else return query select 'BuhurtOS'::text, 'You have a new notification.'::text;
  end if;
end $$;
revoke execute on function private.notification_category(text), private.notification_pushable(text), private.notification_is_synthetic(jsonb),
  private.notification_route(text, jsonb), private.notification_text(text, jsonb) from public, anon, authenticated;

-- Every notification, whichever function wrote it, gets its group, its tap destination and its push decision here. One choke point, so the older
-- producers (team requests, registrations, claims) need no change.
create or replace function private.notifications_prepare() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  new.category := private.notification_category(new.kind);
  if new.route is null then new.route := private.notification_route(new.kind, new.payload); end if;
  if private.notification_pushable(new.kind) and not private.notification_is_synthetic(new.payload) then
    new.push := true; new.push_state := 'pending';
  else
    new.push := false; new.push_state := 'none';
  end if;
  return new;
end $$;
revoke execute on function private.notifications_prepare() from public, anon, authenticated;
do $do$
begin
  if not exists (select 1 from pg_trigger where tgname = 'notifications_prepare' and tgrelid = 'public.notifications'::regclass) then
    create trigger notifications_prepare before insert on public.notifications for each row execute function private.notifications_prepare();
  end if;
end $do$;

-- ---------------------------------------------------------------- 3. waking the dispatcher (best effort, after commit)
-- pg_net queues the request and sends it AFTER the surrounding transaction commits, so a slow or failing dispatcher cannot hold a result or a queue change.
-- Without pg_net or without configuration this does nothing, and the one-minute sweep (scheduled on the hosted project) picks pending items up instead.
create or replace function private.push_kick() returns void
language plpgsql security definer set search_path = '' as $$
declare v_url text; v_secret text;
begin
  select value into v_url from private.push_config where key = 'function_url';
  select value into v_secret from private.push_config where key = 'dispatch_secret';
  if v_url is null or v_secret is null then return; end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'net' and p.proname = 'http_post') then return; end if;
  execute 'select net.http_post(url := $1, body := $2, headers := $3)'
    using v_url, '{}'::jsonb, jsonb_build_object('Content-Type', 'application/json', 'x-dispatch-secret', v_secret);
exception when others then
  raise warning 'push kick failed: %', sqlerrm;
end $$;
revoke execute on function private.push_kick() from public, anon, authenticated;

-- The sweep: only calls out when something is actually waiting (or a send got stuck), so an idle system makes no requests.
create or replace function private.push_sweep() returns void
language plpgsql security definer set search_path = '' as $$
begin
  if exists (select 1 from public.notifications where push_state = 'pending')
     or exists (select 1 from public.push_deliveries where state = 'retry' or (state = 'sending' and claimed_at < now() - interval '2 minutes')) then
    perform private.push_kick();
  end if;
end $$;
revoke execute on function private.push_sweep() from public, anon, authenticated;

create or replace function private.notifications_kick() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if exists (select 1 from new_rows where push_state = 'pending') then perform private.push_kick(); end if;
  return null;
end $$;
revoke execute on function private.notifications_kick() from public, anon, authenticated;
do $do$
begin
  if not exists (select 1 from pg_trigger where tgname = 'notifications_kick' and tgrelid = 'public.notifications'::regclass) then
    create trigger notifications_kick after insert on public.notifications referencing new table as new_rows for each statement execute function private.notifications_kick();
  end if;
end $do$;

-- ---------------------------------------------------------------- 4. devices and settings (the signed-in person, their own rows only)
create or replace function public.register_push_device(p_endpoint text, p_p256dh text, p_auth text, p_label text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_label text; v_id uuid; v_n integer;
begin
  if v_uid is null then raise exception 'sign in required' using errcode = '28000'; end if;
  if p_endpoint is null or p_endpoint !~ '^https://[^[:space:]]+$' or char_length(p_endpoint) > 2048 then raise exception 'that device did not give a usable address' using errcode = '22023'; end if;
  if p_p256dh is null or p_p256dh !~ '^[A-Za-z0-9_-]{60,100}$' or p_auth is null or p_auth !~ '^[A-Za-z0-9_-]{16,32}$' then raise exception 'that device did not give usable keys' using errcode = '22023'; end if;
  v_label := left(btrim(regexp_replace(coalesce(p_label, ''), '[[:cntrl:]]', '', 'g')), 40);
  if v_label = '' then v_label := 'This device'; end if;
  -- The same browser installation signing in as someone else takes the registration over: it is one device, with one owner at a time.
  select count(*) into v_n from public.push_subscriptions where user_id = v_uid and revoked_at is null and endpoint <> p_endpoint;
  if v_n >= 10 then raise exception 'you already have 10 devices; remove one in Notification settings first' using errcode = '22023'; end if;
  insert into public.push_subscriptions (user_id, endpoint, endpoint_digest, p256dh, auth, label)
  values (v_uid, p_endpoint, encode(sha256(convert_to(p_endpoint, 'UTF8')), 'hex'), p_p256dh, p_auth, v_label)
  on conflict (endpoint) do update set user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth, label = excluded.label,
    last_seen_at = now(), failure_count = 0, revoked_at = null
  returning id into v_id;
  insert into public.notification_preferences (user_id) values (v_uid) on conflict (user_id) do nothing;
  return jsonb_build_object('id', v_id);
end $$;

-- Scrubs the secret parts at once: after this the row is a harmless tombstone that the dispatcher cleans up later.
create or replace function private.revoke_subscription(p_id uuid) returns void
language sql security definer set search_path = '' as $$
  update public.push_subscriptions set revoked_at = now(), endpoint = 'revoked:' || id::text, p256dh = '', auth = '' where id = p_id and revoked_at is null
$$;
revoke execute on function private.revoke_subscription(uuid) from public, anon, authenticated;

create or replace function public.remove_push_device(p_id uuid default null, p_endpoint text default null) returns integer
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); r record; v_n integer := 0;
begin
  if v_uid is null then raise exception 'sign in required' using errcode = '28000'; end if;
  if p_id is null and p_endpoint is null then raise exception 'say which device' using errcode = '22023'; end if;
  for r in select id from public.push_subscriptions where user_id = v_uid and revoked_at is null and (id = p_id or endpoint = p_endpoint) loop
    perform private.revoke_subscription(r.id); v_n := v_n + 1;
  end loop;
  return v_n;
end $$;

-- A person's own devices, never with the endpoint or keys. endpoint_digest lets the device recognise itself ("This device").
create or replace function public.my_push_devices() returns table (id uuid, label text, endpoint_digest text, created_at timestamptz, last_success_at timestamptz)
language sql stable security definer set search_path = '' as $$
  select s.id, s.label, s.endpoint_digest, s.created_at, s.last_success_at
  from public.push_subscriptions s where s.user_id = auth.uid() and s.revoked_at is null order by s.created_at
$$;

create or replace function public.my_notification_settings() returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('fights', coalesce(p.fights, true), 'team', coalesce(p.team, true), 'events', coalesce(p.events, true), 'system', coalesce(p.system, true))
  from (select 1) one left join public.notification_preferences p on p.user_id = auth.uid()
$$;

create or replace function public.set_notification_settings(p_fights boolean, p_team boolean, p_events boolean, p_system boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'sign in required' using errcode = '28000'; end if;
  insert into public.notification_preferences (user_id, fights, team, events, system, updated_at)
  values (v_uid, coalesce(p_fights, true), coalesce(p_team, true), coalesce(p_events, true), coalesce(p_system, true), now())
  on conflict (user_id) do update set fights = excluded.fights, team = excluded.team, events = excluded.events, system = excluded.system, updated_at = now();
  return public.my_notification_settings();
end $$;

-- The public half of the VAPID key (public by design: the browser needs it to subscribe). Null until the dispatcher has generated the pair.
create or replace function public.push_public_key() returns text
language sql stable security definer set search_path = '' as $$ select value from private.push_config where key = 'vapid_public' $$;

-- A self-addressed test notification (system group) so a person can prove their phone receives alerts. Once every 20 seconds.
create or replace function public.send_test_notification() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_id uuid; v_devices integer;
begin
  if v_uid is null then raise exception 'sign in required' using errcode = '28000'; end if;
  if exists (select 1 from public.notifications where user_id = v_uid and kind = 'test_push' and created_at > now() - interval '20 seconds') then
    raise exception 'wait a few seconds before sending another test' using errcode = '22023'; end if;
  select count(*) into v_devices from public.push_subscriptions where user_id = v_uid and revoked_at is null;
  insert into public.notifications (user_id, kind, payload) values (v_uid, 'test_push', '{}'::jsonb) returning id into v_id;
  return jsonb_build_object('id', v_id, 'devices', v_devices);
end $$;

-- The list the bell shows: the person's own notifications with ready-made text and the page a tap opens.
create or replace function public.my_notification_feed(p_limit int default 50)
returns table (id uuid, kind text, category text, title text, body text, route text, payload jsonb, created_at timestamptz, read_at timestamptz)
language sql stable security definer set search_path = '' as $$
  select n.id, n.kind, coalesce(n.category, private.notification_category(n.kind)), t.title, t.body, coalesce(n.route, private.notification_route(n.kind, n.payload)), n.payload, n.created_at, n.read_at
  from public.notifications n cross join lateral private.notification_text(n.kind, n.payload) t
  where n.user_id = auth.uid()
  order by n.created_at desc limit least(greatest(coalesce(p_limit, 50), 1), 200)
$$;

