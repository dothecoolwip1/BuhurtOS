-- Pack 12 (2026-10-06), part 2 of 2: web push for the installed app, notification settings, and the server-side producers.
-- Additive. Requires part 1 (20261006000100).
--
-- Principles
--   * The database stays authoritative. A fight notification is derived from a REAL change of matches.queue_state / matches.field (the same columns the
--     "My next fight" screen and the field queue read), inside the transaction that made the change. There is no second scheduler and no clock.
--   * Delivery is a convenience layer. Producing a notification can never fail or slow the queue, a result or a registration: every producer swallows its
--     own errors. Push dispatch happens afterwards, outside the sporting transaction, by an Edge Function that only the database can call.
--   * Device subscriptions are secrets: no client can read them, not even the owner. Clients register, list (without endpoint or keys) and remove their own
--     devices through functions. Notification content for push is short and carries no health, contact, waiver or account data.
--   * Synthetic / test events and teams never push (their notifications still reach the in-app list, labelled by the event itself).
--
-- Nothing here removes or rewrites a sporting record.

-- ---------------------------------------------------------------- 1. tables
create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  endpoint text not null unique check (char_length(endpoint) <= 2048),
  endpoint_digest text not null,
  p256dh text not null,
  auth text not null,
  label text not null default 'This device' check (char_length(label) <= 40),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  last_success_at timestamptz,
  failure_count integer not null default 0,
  revoked_at timestamptz
);
alter table public.push_subscriptions enable row level security;
create index if not exists push_subscriptions_user_idx on public.push_subscriptions (user_id) where revoked_at is null;
revoke all on public.push_subscriptions from public, anon, authenticated;
comment on table public.push_subscriptions is 'One row per browser/phone installation that agreed to notifications. Secret: never granted to clients; read and written only through functions. A revoked row is a tombstone with its endpoint and keys scrubbed.';

create table if not exists public.notification_preferences (
  user_id uuid primary key references auth.users (id) on delete cascade,
  fights boolean not null default true,
  team boolean not null default true,
  events boolean not null default true,
  system boolean not null default true,
  updated_at timestamptz not null default now()
);
alter table public.notification_preferences enable row level security;
revoke all on public.notification_preferences from public, anon, authenticated;

create table if not exists public.push_deliveries (
  notification_id uuid not null references public.notifications (id) on delete cascade,
  subscription_id uuid not null references public.push_subscriptions (id) on delete cascade,
  state text not null default 'sending' check (state in ('sending', 'retry', 'sent', 'failed', 'gone')),
  attempts integer not null default 1,
  last_error text,
  claimed_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (notification_id, subscription_id)
);
alter table public.push_deliveries enable row level security;
revoke all on public.push_deliveries from public, anon, authenticated;

-- Server-only settings: the dispatch secret, the function URL and the VAPID key pair (generated by the Edge Function the first time it runs,
-- so the private key never appears in the repository, a browser bundle or a chat). The private schema is not exposed through the API.
create table if not exists private.push_config (key text primary key, value text not null, updated_at timestamptz not null default now());
revoke all on private.push_config from public, anon, authenticated;
